/// Raster geometry and command payloads for one S1300i protocol resolution.
/// All strides are in bytes; widths and heights are in pixels at the protocol
/// resolution. A raw line holds three colour planes, each interleaving the
/// front and back sensor per pixel.
nonisolated struct EpjitsuResolutionSettings: Equatable, Sendable {
    let xResolution: Int
    let yResolution: Int
    let maxWidth: Int
    let maxHeight: Int
    let lineStride: Int
    let planeStride: Int
    let planeWidth: Int
    let blockHeight: Int
    let calibrationLineStride: Int
    let calibrationPlaneStride: Int
    let calibrationPlaneWidth: Int
    let coarseCalibrationWindow: [UInt8]
    let fineCalibrationWindow: [UInt8]
    let sendCalibrationWindow: [UInt8]
    let scanWindow: [UInt8]
    let gainHeader: [UInt8]
    let offsetHeader: [UInt8]
    /// On AC power the S1300i delivers its green and blue planes one and two
    /// pixels late at 225 and 300 dpi; image data (not calibration data) has
    /// to be read with that offset.
    let shiftsColorPlanes: Bool

    /// The SET WINDOW payload for the image scan with the requested height.
    func scanWindow(height: Int) -> Data {
        var bytes = scanWindow
        for index in 0..<4 {
            bytes[0x1a + index] = UInt8((height >> ((3 - index) * 8)) & 0xff)
        }
        return Data(bytes)
    }

    /// Picks the smallest protocol resolution that covers the request, as the
    /// vendor driver does (200 dpi is scanned at 225 x 200).
    static func s1300i(usbPower: Bool, requestedResolution: Int) throws -> Self {
        let candidates = usbPower ? onUSBPower : onACPower
        guard let settings = candidates.first(where: {
            $0.xResolution >= requestedResolution && $0.yResolution >= requestedResolution
        }) else {
            throw ScannerError.unsupportedOption("Epjitsu color acquisition does not support \(requestedResolution) dpi.")
        }
        return settings
    }

    private typealias T = EpjitsuProtocolTables

